/**
 * Lightweight i18n layer.
 *
 * Every visible UI string goes through `t()`. Adding a locale means adding a
 * dictionary below — no component changes.
 */

export type Locale = "en" | "kn" | "ar";

/** Flat dot-paths to every leaf string, e.g. `"aiFeatures.explain"`. */
type LeafPaths<T> = {
  [K in keyof T & string]: T[K] extends string ? K : `${K}.${LeafPaths<T[K]>}`;
}[keyof T & string];

/** Any dictionary is a flat-or-nested map of strings. */
type Dict = Record<string, string | Record<string, string>>;

